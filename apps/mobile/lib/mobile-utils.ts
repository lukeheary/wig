function toDate(value: Date | string) {
  return value instanceof Date ? value : new Date(value);
}

export function formatDate(value: Date | string) {
  return new Intl.DateTimeFormat("en-US", {
    month: "short",
    day: "numeric",
    year: "numeric",
  }).format(toDate(value));
}

export function formatTime(value: Date | string) {
  return new Intl.DateTimeFormat("en-US", {
    hour: "numeric",
    minute: "2-digit",
  }).format(toDate(value));
}

export function formatDateTime(value: Date | string) {
  return `${formatDate(value)} at ${formatTime(value)}`;
}

export function splitTrailingParenthetical(text: string): {
  main: string;
  trailingParenthetical: string | null;
} {
  const match = text.match(/^(.*?)(\s*\([^()]+\))$/);

  if (!match) {
    return {
      main: text,
      trailingParenthetical: null,
    };
  }

  return {
    main: match[1],
    trailingParenthetical: match[2].trimStart(),
  };
}

function toVersionToken(value: Date | string | null | undefined) {
  if (!value) return null;
  const date = value instanceof Date ? value : new Date(value);
  const time = date.getTime();
  return Number.isNaN(time) ? null : String(time);
}

export function withImageVersion(
  imageUrl: string | null | undefined,
  updatedAt?: Date | string | null
) {
  if (!imageUrl) return null;

  const version = toVersionToken(updatedAt);
  if (!version) return imageUrl;

  const separator = imageUrl.includes("?") ? "&" : "?";
  return `${imageUrl}${separator}v=${version}`;
}

